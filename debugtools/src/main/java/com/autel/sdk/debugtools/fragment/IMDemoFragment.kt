/**
 * IM message sharing sample Fragment
 *
 * ======================================================================
 * Chat room lifecycle (IMPORTANT!)
 * ======================================================================
 *
 * The IM chat room is not created standalone; it depends on multi-device mesh networking. The flow is:
 *
 * Step 1: Mesh networking — prerequisite
 *   └ After two or more RCs form a mesh network, the system generates a MeshID (network ID)
 *   └ MeshID = channel ID = chat room ID — all RCs in the same network share one MeshID
 *   └ API: DeviceManager.getMultiDeviceOperator().getNetMeshManager().getNetId()
 *
 * Step 2: RTM initialization and connection
 *   └ After networking succeeds, IMUserManager discovers the local RC via onDiscoverReport()
 *   └ The createLocalUser(localUser, localMeshId) callback triggers RTM initialization
 *   └ RTM initializes with userId (RC device ID) + meshId
 *   └ Connection states: kIdle → kConnecting → kConnected
 *
 * Step 3: Join channel — chat room ready
 *   └ After RTM connects (kConnected), auto-join the channel named after the MeshID after 3s
 *   └ API: rtmManager.joinChannel(meshId)
 *
 * Step 4: Conversation auto-creation
 *   └ After joining the channel, the RTM SDK creates a Conversation automatically
 *   └ Get conversationId via the onNewConversation(conversation) callback
 *   └ conversationId is used to query history messages
 *   └ The chat room is now fully ready to send and receive messages
 *
 * ======================================================================
 * Key IDs
 * ======================================================================
 *
 * MeshID (channel ID / chat room ID):
 *   └ Source: auto-generated by the mesh manager
 *   └ Get: DeviceManager.getMultiDeviceOperator().getNetMeshManager().getNetId()
 *   └ Usage: RTM channel name; all RCs in the same network join the same channel
 *   └ Example: "mesh_12345678"
 *
 * UserID (participant ID / device ID):
 *   └ Source: the RC device deviceId
 *   └ Get: meshDevice.deviceId.toString()
 *   └ Usage: unique identity of each RC in the RTM system
 *   └ Note: each RC has a unique deviceId used as the IM participant identity
 *
 * ConversationID:
 *   └ Source: auto-created by the RTM SDK after joining the channel
 *   └ Get: conversation.id in the onNewConversation callback
 *   └ Usage: querying history messages (MessageQueryParams.conversationId)
 *
 * ======================================================================
 *
 * Features:
 * 1. Text messages — send text between RCs
 * 2. Voice messages — hold to record, tap to play
 * 3. Drone telemetry sharing — get lat/lon, altitude, speed etc. and share via custom messages to the other RC
 * 4. Custom data sharing — send custom data via byte array message structure
 *
 * Use cases:
 * - Pilot + observer (1 drone, 2 RCs) — observer views telemetry shared by the pilot RC
 * - Pilot + pilot (2 drones, 2 RCs) — share drone info between pilots
 * - Pilot + observer + pilot (2 drones, 3 RCs) — observer receives telemetry from both drones
 *
 * Dependencies:
 * - com.autel:AMediaManager — RTM communication
 * - com.autel.drone.sdk — drone device management, telemetry access
 */
