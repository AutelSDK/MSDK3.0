     * Show all RC IDs, names and online status
     * Each RC deviceId is its IM participant ID (userId)
     */
    private fun updateParticipantsPanel() {
        if (rcDeviceList.isEmpty()) {
            tvParticipants.text = getString(R.string.im_participants_none)
            return
        }

        val sb = StringBuilder(getString(R.string.im_participants_header))
        rcDeviceList.forEachIndexed { index, rc ->
            if (index > 0) sb.append(" | ")
            val onlineIcon = if (rc.isOnline) "🟢" else "⚪"
            val localTag = if (rc.isLocal) getString(R.string.im_local_device_suffix) else ""
            // Format: 🟢 name(local) [ID:12345]
            sb.append("$onlineIcon ${rc.deviceName}$localTag [ID:${rc.deviceId}]")
        }
        tvParticipants.text = sb.toString()
