    private fun refreshMeshDevices() {
        val netMeshManager = DeviceManager.getMultiDeviceOperator().getNetMeshManager()
        val newMeshId = netMeshManager.getNetId()
        val rcList = netMeshManager.getAllMeshDeviceList().filter { it.isRc() }
        val currentIds = rcList.map { it.deviceId.toString() }.toSet()

        // Detect mesh ID changes
        if (newMeshId != meshId && !newMeshId.isNullOrEmpty()) {
            meshId = newMeshId
            updateMeshStatus(true)
            tvTitle.text = getString(R.string.im_title, meshId)
        }

        // Remove gone devices
        rcDeviceList.removeAll { !currentIds.contains(it.deviceId) }

        // Add new devices
        rcList.forEach { device ->
            val existing = rcDeviceList.find { it.deviceId == device.deviceId.toString() }
            if (existing == null) {
                rcDeviceList.add(
                    RCDevice(device.deviceId.toString(), device.deviceName, device.local)
                )
                if (device.local) {
                    localUserId = device.deviceId.toString()
                    localUserName = device.deviceName
                }
            }
        }

        // Refresh participants panel
        updateParticipantsPanel()
    }

