    private fun getAudioDuration(filePath: String): Int {
        return try {
            val mp = MediaPlayer()
            mp.setDataSource(filePath)
            mp.prepare()
            val dur = mp.duration
            mp.release()
            dur
        } catch (e: Exception) {
            0
        }
    }

    private fun checkAudioPermission(): Boolean {
        val granted = requireContext().checkSelfPermission(Manifest.permission.RECORD_AUDIO) ==
                PackageManager.PERMISSION_GRANTED
        if (!granted) {
            requestPermissions(arrayOf(Manifest.permission.RECORD_AUDIO), 1001)
            toast(getString(R.string.im_mic_permission))
        }
        return granted
    }

