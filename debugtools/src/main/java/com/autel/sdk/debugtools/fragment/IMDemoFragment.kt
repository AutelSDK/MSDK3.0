    /**
     * Handle voice button touch events
     * Press to start recording, release to send
     */
    private fun handleVoiceTouchEvent(event: MotionEvent): Boolean {
        when (event.action) {
            MotionEvent.ACTION_DOWN -> {
                if (checkAudioPermission()) {
                    startRecording()
                    btnVoice.text = "🔴"
                    btnVoice.setBackgroundColor(Color.parseColor("#FFCDD2"))
                }
                return true
            }

            MotionEvent.ACTION_UP, MotionEvent.ACTION_CANCEL -> {
                if (isRecording) {
                    val duration = System.currentTimeMillis() - recordStartTime
                    if (duration < 1000) {
                        stopRecording(send = false)
                        toast(getString(R.string.im_record_too_short))
                    } else {
                        stopRecording(send = true)
                    }
                }
                btnVoice.text = "🎤"
                btnVoice.setBackgroundColor(Color.parseColor("#E0E0E0"))
                return true
            }
        }
        return false
    }

    /**
     * Start recording
     * Uses standard Android MediaRecorder
     */
    private fun startRecording() {
        try {
            val audioDir = File(requireContext().filesDir, "im_demo_audio")
            if (!audioDir.exists()) audioDir.mkdirs()
            audioFilePath = File(audioDir, "${System.currentTimeMillis()}.m4a").absolutePath

            mediaRecorder = MediaRecorder().apply {
                setAudioSource(MediaRecorder.AudioSource.MIC)
                setOutputFormat(MediaRecorder.OutputFormat.MPEG_4)
                setAudioEncoder(MediaRecorder.AudioEncoder.AAC)
                setAudioSamplingRate(16000)
                setAudioEncodingBitRate(64000)
                setOutputFile(audioFilePath)
                prepare()
                start()
            }
            isRecording = true
            recordStartTime = System.currentTimeMillis()
        } catch (e: Exception) {
            toast(getString(R.string.im_record_start_failed, e.message))
            isRecording = false
        }
    }

    /**
     * Stop recording
     * @param send whether to send the voice message
     */
    private fun stopRecording(send: Boolean) {
        if (!isRecording) return
        isRecording = false
        val recordDurationMs = System.currentTimeMillis() - recordStartTime

        try {
            mediaRecorder?.apply {
                stop()
                release()
            }
        } catch (e: Exception) {
            // ignore
        }
        mediaRecorder = null

        if (send && audioFilePath != null) {
            sendVoiceMessage(audioFilePath!!, recordDurationMs)
        }
    }

    /**
     * Send voice message
     *
     * @param filePath recording file path
     * @param fallbackDurationMs duration (ms) computed from recordStartTime,
     *        used as fallback when MediaPlayer cannot read the file duration
     *
     * API: ARTMMessageManager.createAudioMessage() + rtmManager.sendMessage()
     */
    private fun sendVoiceMessage(filePath: String, fallbackDurationMs: Long = 0L) {
        if (!isRtmConnected || meshId == null) {
            toast(getString(R.string.im_rtm_not_connected))
            return
        }

        val file = File(filePath)
        if (!file.exists()) return

        lastSentAudioPath = filePath
        val fileName = file.name

        // MediaPlayer may return 0 duration because the file is not fully flushed;
        // fall back to the duration computed from recordStartTime
        val mpDuration = getAudioDuration(filePath)
        val duration = if (mpDuration > 0) mpDuration.toLong() else fallbackDurationMs

        val voiceMsg = ARTMMessageManager.getInstance().createAudioMessage(
            filePath, fileName, file.length(), duration, "m4a"
        )

        rtmManager.sendMessage(voiceMsg, meshId!!, "", object : ARTMSendCallback<Message> {
            override fun onProgress(progress: Int) {}

            override fun onSuccess(message: Message) {
                mainHandler.post {
                    displayMessage(message)
                    toast(getString(R.string.im_voice_send_success))
                }
            }

            override fun onError(code: Int, desc: String) {
                mainHandler.post { toast(getString(R.string.im_voice_send_failed, desc)) }
            }
        })
    }

    /**
     * Play voice message
     */
    private fun playVoiceMessage(message: Message) {
        val attachment = message.attachments.firstOrNull() as? AudioAttachment ?: return

        // Own message: prefer the last sent local path, then attachment.localUrl
        if (message.isOwnMessage) {
            val candidates = listOfNotNull(lastSentAudioPath, attachment.localUrl.takeIf { it.isNotEmpty() })
            val validPath = candidates.firstOrNull { File(it).exists() }
            if (validPath != null) {
                playLocalAudio(validPath)
                return
            }
        }

        // Remote message or missing local file: download then play (m4a)
        val localPath = File(requireContext().filesDir, "im_demo_audio/${message.id}.m4a").absolutePath
        if (File(localPath).exists()) {
            playLocalAudio(localPath)
            return
        }

        toast(getString(R.string.im_downloading_voice))
        attachment.downloadAudio(localPath, object : com.autel.rtm.ARTMDownloadCallback<String> {
            override fun onSuccess(path: String) {
                mainHandler.post { playLocalAudio(path) }
            }

            override fun onError(code: Int, desc: String) {
                mainHandler.post { toast(getString(R.string.im_download_failed, desc)) }
            }

            override fun onProgress(current: Long, total: Long) {}
        })
    }

    private fun playLocalAudio(filePath: String) {
        releaseMediaPlayer()
        try {
            mediaPlayer = MediaPlayer().apply {
                setDataSource(filePath)
                prepare()
                start()
                setOnCompletionListener {
                    toast(getString(R.string.im_playback_done))
                    releaseMediaPlayer()
                }
            }
            toast(getString(R.string.im_playing))
        } catch (e: Exception) {
            toast(getString(R.string.im_playback_failed, e.message))
        }
    }

    private fun releaseMediaPlayer() {
        mediaPlayer?.apply {
            if (isPlaying) stop()
            release()
        }
        mediaPlayer = null
    }

