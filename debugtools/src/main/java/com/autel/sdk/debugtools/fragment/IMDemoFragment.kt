    /**
     * Fetch and share drone telemetry
     *
     * Key APIs:
     * - CommonKey.KeyPosAndAttitudeReport — drone position and attitude
     * - device.getKeyManager().getCacheValue() — cached telemetry
     * - ARTMMessageManager.createCustomMessage() — create custom message
     */
    private fun shareTelemetryData() {
        val drones = DeviceManager.getDeviceManager().getDroneDevices()
        if (drones.isEmpty()) {
            toast(getString(R.string.im_no_drone_connected))
            return
        }

        val droneIndex = if (selectedDroneIndex >= 0 && selectedDroneIndex < drones.size)
            selectedDroneIndex else 0
        val drone = drones[droneIndex]

        if (!drone.isConnected()) {
            toast(getString(R.string.im_drone_not_connected))
            return
        }

        // Get position and attitude data
        val posKey = CommonKey.KeyPosAndAttitudeReport.create()
        val posData = drone.getKeyManager()?.getCacheValue(posKey)
            ?: PosAndAttitudeReportBean()

        val telemetry = TelemetryData(
            deviceId = drone.getDeviceNumber(),
            deviceName = drone.getDeviceInfoBean()?.deviceName ?: getString(R.string.im_unknown_drone),
            latitude = posData.latitude,
            longitude = posData.longitude,
            altitude = posData.altitude,
            altitudeMSL = posData.altitudeMSL,
            speedX = posData.localVelocity.x,
            speedY = posData.localVelocity.y,
            speedZ = posData.localVelocity.z,
            yaw = posData.droneAttitude.yaw,
            pitch = posData.droneAttitude.pitch,
            roll = posData.droneAttitude.roll
        )

        // Serialize to JSON and send as custom message
        val jsonStr = gson.toJson(telemetry)
        sendCustomMessage(jsonStr, getString(R.string.im_telemetry_label))
    }

