    /**
     * RTM connection state listener
     *
     * State flow: kIdle → kConnecting → kConnected → (possibly kDisconnected)
     *
     * Key flow:
     * - kConnected: RTM connected → delayed channel join (meshId)
     * - After joining: onNewConversation fires to create the conversation
     * - User changes in channel: updated via onUsersUpdate callback
     */
    private val rtmListener = object : RtmListener {
        override fun onStateChange(state: RtmState) {
            mainHandler.post {
                when (state) {
                    RtmState.kConnected -> {
                        isRtmConnected = true
                        updateStatus(getString(R.string.im_status_connected), Color.parseColor("#4CAF50"))
                        updateRtmStatus(getString(R.string.im_rtm_connected), Color.parseColor("#4CAF50"))
                        // ============================================================
                        // Join channel after RTM connects (delayed)
                        // Channel ID = meshId; devices in the same network join it to exchange messages
                        // A Conversation is created automatically after joining
                        // ============================================================
                        mainHandler.postDelayed({
                            meshId?.let { rtmManager.joinChannel(it) }
                        }, 2000)
                    }

                    RtmState.kDisconnected -> {
                        isRtmConnected = false
                        updateStatus(getString(R.string.im_status_disconnected), Color.RED)
                        updateRtmStatus(getString(R.string.im_rtm_disconnected), Color.RED)
                    }

                    RtmState.kConnecting -> {
                        updateStatus(getString(R.string.im_status_connecting), Color.parseColor("#FF9800"))
                        updateRtmStatus(getString(R.string.im_status_connecting), Color.parseColor("#FF9800"))
                    }

                    else -> {
                        updateStatus(getString(R.string.im_rtm_state, state), Color.GRAY)
                        updateRtmStatus("$state", Color.GRAY)
                    }
                }
            }
        }

        /**
         * Channel users update callback
         *
         * @param channelId channel ID (= meshId)
         * @param users all users in the channel, key = userId (device ID)
         *
         * Note: keys in the users map are the RC deviceIds (participant IDs)
         */
        override fun onUsersUpdate(channelId: String, users: Map<String, UserProfile>) {
            mainHandler.post {
                // Update online status
                rcDeviceList.forEach { rc ->
                    rc.isOnline = users.containsKey(rc.deviceId)
                }
                refreshDeviceTabs()
                val onlineCount = rcDeviceList.count { it.isOnline }
                tvTitle.text = getString(R.string.im_title_with_count, meshId, onlineCount, rcDeviceList.size)
                // Update participants panel
                updateParticipantsPanel()
            }
        }
    }

    /**
     * Conversation listener
     *
     * After RTM joins a channel, the SDK creates or restores a Conversation automatically.
     * conversationId uniquely identifies the chat room session, used for history queries.
     *
     * Distinguish:
     * - meshId (channel ID): target for joining and sending messages
     * - conversationId: used to query history messages
     * They usually differ; conversationId is generated inside the RTM SDK.
     */
    private val conversationListener = object : ARTMConversationListener {
        override fun onNewConversation(conversation: Conversation) {
            // ============================================================
            // Conversation created = chat room fully ready!
            // Can now send messages and query history
            // ============================================================
            conversationId = conversation.id
            mainHandler.post {
                updateConversationStatus()
                loadHistoryMessages()
            }
        }

        override fun onConversationUpdated(conversation: Conversation) {
            conversationId = conversation.id
            mainHandler.post { updateConversationStatus() }
        }
    }

