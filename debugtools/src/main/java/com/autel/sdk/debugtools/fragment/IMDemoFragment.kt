    /**
     * Show a message in the chat area
     */
    private fun displayMessage(message: Message) {
        val isOwn = message.isOwnMessage
        val container = LinearLayout(requireContext()).apply {
            orientation = LinearLayout.VERTICAL
            setPadding(dp(8), dp(4), dp(8), dp(4))
            gravity = if (isOwn) Gravity.END else Gravity.START
        }

        // Sender name + time
        val header = TextView(requireContext()).apply {
            val senderName = if (isOwn) getString(R.string.im_sender_me) else (message.senderName ?: message.senderId ?: getString(R.string.im_unknown))
            val time = SimpleDateFormat("HH:mm:ss", Locale.getDefault()).format(Date(message.createdAt))
            text = "$senderName · $time"
            textSize = 11f
            setTextColor(Color.GRAY)
            gravity = if (isOwn) Gravity.END else Gravity.START
        }
        container.addView(header)

        // Message bubble
        val bubble = createMessageBubble(message, isOwn)
        container.addView(bubble)

        llMessages.addView(container)

        // Scroll to bottom
        svMessages.post { svMessages.fullScroll(View.FOCUS_DOWN) }
    }

    /**
     * Create different bubble views by message type
     */
    private fun createMessageBubble(message: Message, isOwn: Boolean): View {
        return when (message.type) {
            MessageType.TEXT.value -> createTextBubble(message.content ?: "", isOwn)

            MessageType.AUDIO.value -> createVoiceBubble(message, isOwn)

            MessageType.CUSTOM.value -> createCustomBubble(message, isOwn)

            else -> createTextBubble(getString(R.string.im_unsupported_message_type, message.type), isOwn)
        }
    }

    private fun createTextBubble(text: String, isOwn: Boolean): TextView {
        return TextView(requireContext()).apply {
            this.text = text
            textSize = 14f
            setTextColor(if (isOwn) Color.WHITE else Color.parseColor("#333333"))
            setBackgroundColor(if (isOwn) Color.parseColor("#4C55FF") else Color.WHITE)
            setPadding(dp(12), dp(8), dp(12), dp(8))
            maxWidth = dp(260)
        }
    }

    private fun createVoiceBubble(message: Message, isOwn: Boolean): TextView {
        val attachment = message.attachments.firstOrNull() as? AudioAttachment
        val durationSec = (attachment?.duration ?: 0) / 1000
        return TextView(requireContext()).apply {
            text = getString(R.string.im_voice_message_bubble, durationSec)
            textSize = 14f
            setTextColor(if (isOwn) Color.WHITE else Color.parseColor("#333333"))
            setBackgroundColor(if (isOwn) Color.parseColor("#3F51B5") else Color.WHITE)
            setPadding(dp(12), dp(8), dp(12), dp(8))
            setOnClickListener { playVoiceMessage(message) }
        }
    }

    private fun createCustomBubble(message: Message, isOwn: Boolean): LinearLayout {
        val content = message.content ?: "{}"
        val layout = LinearLayout(requireContext()).apply {
            orientation = LinearLayout.VERTICAL
            setBackgroundColor(if (isOwn) Color.parseColor("#FF9800") else Color.parseColor("#FFF3E0"))
            setPadding(dp(12), dp(8), dp(12), dp(8))
        }

        // Try to parse as telemetry
        try {
            // Check the type field first
            val baseObj = gson.fromJson(content, Map::class.java)
            val typeVal = (baseObj["type"] as? Double)?.toInt()

            when (typeVal) {
                MSG_TYPE_TELEMETRY -> {
                    val data = gson.fromJson(content, TelemetryData::class.java)
                    val textColor = if (isOwn) Color.WHITE else Color.parseColor("#E65100")

                    layout.addView(TextView(requireContext()).apply {
                        text = getString(R.string.im_telemetry_bubble_title, data.deviceName)
                        textSize = 13f
                        setTextColor(textColor)
                        setTypeface(null, Typeface.BOLD)
                    })
                    layout.addView(TextView(requireContext()).apply {
                        text = buildString {
                            append(getString(R.string.im_telemetry_lon_lat).format(data.longitude, data.latitude))
                            append(getString(R.string.im_telemetry_altitude).format(data.altitude, data.altitudeMSL))
                            append(getString(R.string.im_telemetry_speed).format(data.speedX, data.speedY, data.speedZ))
                            append(getString(R.string.im_telemetry_attitude).format(data.yaw, data.pitch, data.roll))
                        }
                        textSize = 12f
                        setTextColor(textColor)
                    })
                }

                MSG_TYPE_CUSTOM_DATA -> {
                    val data = gson.fromJson(content, CustomDataMessage::class.java)
                    val textColor = if (isOwn) Color.WHITE else Color.parseColor("#E65100")

                    layout.addView(TextView(requireContext()).apply {
                        text = getString(R.string.im_custom_data_bubble_title, data.senderName)
                        textSize = 13f
                        setTextColor(textColor)
                        setTypeface(null, Typeface.BOLD)
                    })
                    layout.addView(TextView(requireContext()).apply {
                        text = buildString {
                            append(getString(R.string.im_custom_data_description, data.description))
                            append("Payload (Base64): ${data.payload.take(40)}...")
                            // decode example
                            try {
                                val bytes = android.util.Base64.decode(data.payload, android.util.Base64.NO_WRAP)
                                append(getString(R.string.im_custom_data_raw_bytes, bytes.size, bytes.joinToString(" ") { "%02X".format(it) }))
                            } catch (_: Exception) {}
                        }
                        textSize = 12f
                        setTextColor(textColor)
                    })
                }

                else -> {
                    layout.addView(TextView(requireContext()).apply {
                        text = getString(R.string.im_custom_message, content.take(100))
                        textSize = 12f
                        setTextColor(Color.parseColor("#333333"))
                    })
                }
            }
        } catch (e: Exception) {
            layout.addView(TextView(requireContext()).apply {
                text = getString(R.string.im_custom_message, content.take(100))
                textSize = 12f
                setTextColor(Color.parseColor("#333333"))
            })
        }

        return layout
    }

