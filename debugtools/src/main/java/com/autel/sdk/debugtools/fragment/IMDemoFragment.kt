    /**
     * Send text message
     *
     * API: ARTMMessageManager.createTextMessage() + rtmManager.sendMessage()
     */
    private fun sendTextMessage(text: String) {
        if (!isRtmConnected || meshId == null) {
            toast(getString(R.string.im_rtm_not_connected_wait))
            return
        }

        val textMsg = ARTMMessageManager.getInstance().createTextMessage(text)
        rtmManager.sendMessage(textMsg, meshId!!, "", object : ARTMSendCallback<Message> {
            override fun onProgress(progress: Int) {}

            override fun onSuccess(message: Message) {
                mainHandler.post {
                    displayMessage(message)
                    toast(getString(R.string.im_send_success))
                }
            }

            override fun onError(code: Int, desc: String) {
                mainHandler.post { toast(getString(R.string.im_send_failed, desc)) }
            }
        })
    }

