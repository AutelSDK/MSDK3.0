    /**
     * Initialize RTM communication
     *
     * Lifecycle steps:
     * 1. Check mesh status — the chat room depends on networking
     * 2. Get MeshID — auto-generated after networking, used as RTM channel (chat room) ID
     * 3. Get participants — each RC deviceId becomes the userId (participant ID)
     * 4. Initialize RTM — configure with userId + meshId
     * 5. Wait for connection → auto join channel → auto create conversation → chat room ready
     */
    private fun initRTM() {
        // Register RTM listeners
        rtmManager.addRtmListener(rtmListener)
        rtmManager.addConversationListener(conversationListener)
        // Register message listeners
        rtmManager.addMessageListener(messageListener)

        // ============================================================
        // Step 1: get meshId (channel/chat room ID) from the mesh manager
        // meshId is auto-generated; all RCs in the same network share it
        // ============================================================
        val netMeshManager = DeviceManager.getMultiDeviceOperator().getNetMeshManager()
        meshId = netMeshManager.getNetId()

        // ============================================================
        // Step 2: get participants — RC device list
        // Each RC deviceId becomes the userId (participant ID) in the IM system
        // device.local == true means the current device (local RC)
        // ============================================================
        val allMeshDevices = netMeshManager.getAllMeshDeviceList()
        val rcList = allMeshDevices.filter { it.isRc() }

        rcList.forEach { device ->
            val rc = RCDevice(
                deviceId = device.deviceId.toString(),
                deviceName = device.deviceName,
                isLocal = device.local
            )
            rcDeviceList.add(rc)
            if (device.local) {
                localUserId = rc.deviceId
                localUserName = rc.deviceName
            }
        }

        // Update mesh status panel
        if (meshId.isNullOrEmpty()) {
            // Not networked — chat room cannot be created
            // Tap the status text to open the mesh setup dialog
            updateStatus(getString(R.string.im_not_in_mesh), Color.RED)
            updateMeshStatus(false)

            // ============================================================
            // Tap the "not networked" hint → open mesh setup dialog
            // In the dialog choose "Create network" or "Join network" to complete mesh networking
            // After success it returns here and initializes RTM / creates the chat room
            // ============================================================
            tvStatus.setOnClickListener { showMeshSetupDialog() }
            tvMeshStatus.setOnClickListener { showMeshSetupDialog() }
            return
        }

        // Networking done; show network info
        updateMeshStatus(true)

        // ============================================================
        // Step 3: RTM configuration
        // - userId: local RC deviceId as the unique participant identity
        // - meshId is used for joinChannel() after connection
        // - isRTNEnabled(true): enable RTN networking mode
        // ============================================================
        val config = ARTMConfig.Builder()
            .context(requireContext().applicationContext)
            .appId(requireContext().packageName)
            .userId(localUserId ?: "unknown")     // participant ID = RC deviceId
            .userName(localUserName ?: getString(R.string.im_unknown_device))  // participant name = RC name
            .rtmServerUrl("127.0.0.1")
            .dataBasePath("${requireContext().filesDir}/im_demo_rtm.realm")
            .isRTNEnabled(true) // enable RTN networking
            .build()

        rtmManager.init(config)
        isRtmInitialized = true
        updateStatus(getString(R.string.im_rtm_initializing), Color.parseColor("#FF9800"))
        updateRtmStatus(getString(R.string.im_status_initializing), Color.parseColor("#FF9800"))

        tvTitle.text = getString(R.string.im_title, meshId)

        // Clear the status text click event (networked; no longer needed)
        tvStatus.setOnClickListener(null)
        tvMeshStatus.setOnClickListener(null)
    }

