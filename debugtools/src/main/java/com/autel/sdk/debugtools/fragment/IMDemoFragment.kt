    /**
     * Custom data sending example
     *
     * Customers can wrap their app protocol data into a byte array,
     * Base64-encode it and put it in the payload field to send via IM
     *
     * Example: send custom coordinate point data
     */
    private fun sendCustomDataDemo() {
        // Example: build a custom packet (simulating a customer protocol)
        val samplePayload = byteArrayOf(
            0x01,                         // protocol version
            0x02,                         // message type: coordinates
            0x00, 0x10,                   // data length: 16 bytes
            // longitude (simplified first 4 bytes of a double)
            0x40, 0x5E, 0x00, 0x00,
            // latitude (simplified first 4 bytes of a double)
            0x40, 0x3E, 0x00, 0x00,
            // altitude (float)
            0x42, 0xC8.toByte(), 0x00, 0x00,
            // checksum
            0x00, 0x00, 0x00, 0xFF.toByte()
        )

        val customData = CustomDataMessage(
            senderId = localUserId ?: "",
            senderName = localUserName ?: getString(R.string.im_unknown),
            payload = android.util.Base64.encodeToString(samplePayload, android.util.Base64.NO_WRAP),
            description = getString(R.string.im_custom_coord_data_desc)
        )

        val jsonStr = gson.toJson(customData)
        sendCustomMessage(jsonStr, getString(R.string.im_custom_data_label))
    }

